using System.Net;
using System.Text;
using CrowdFund.Core.Entities;

namespace CrowdFund.Core.Services;

/// <summary>
/// Builds tax-oriented donation receipts (HTML). Includes 80G / 501(c)(3) fields when present.
/// PDF can be generated client-side print or a later QuestPDF step.
/// </summary>
public class TaxReceiptService
{
    public DonationTaxInfo BuildTaxInfo(
        Donation donation,
        Campaign campaign,
        CreatorProfile? creator,
        string? donorLegalName,
        string? donorAddress,
        string? donorTaxId)
    {
        var eligible = creator is { IsNonprofit: true }
                       && !string.IsNullOrWhiteSpace(creator.TaxExemptionNumber)
                       && (creator.TaxExemptionValidUntil == null || creator.TaxExemptionValidUntil > DateTime.UtcNow);

        var receiptNo = $"CF-{donation.CapturedAt?.ToString("yyyyMMdd") ?? DateTime.UtcNow.ToString("yyyyMMdd")}-{donation.Id.ToString("N")[..8].ToUpperInvariant()}";

        return new DonationTaxInfo
        {
            DonationId = donation.Id,
            IsEligibleForTaxReceipt = eligible,
            ExemptionType = creator?.TaxExemptionType,
            ExemptionNumber = creator?.TaxExemptionNumber,
            OrgTaxId = creator?.TaxId,
            OrgLegalName = creator?.OrganizationName ?? creator?.LegalName,
            DonorLegalName = donorLegalName,
            DonorAddress = donorAddress,
            DonorTaxId = donorTaxId,
            ReceiptNumber = receiptNo,
            IssuedAt = DateTime.UtcNow
        };
    }

    public string RenderHtml(
        Donation donation,
        Campaign campaign,
        DonationTaxInfo tax,
        string? ledgerHeadHash = null)
    {
        var sb = new StringBuilder();
        sb.Append("""
<!DOCTYPE html><html><head><meta charset="utf-8"><title>Donation Receipt</title>
<style>
body{font-family:system-ui,Segoe UI,sans-serif;max-width:720px;margin:2rem auto;color:#2D3436;line-height:1.45}
h1{color:#6C5CE7;margin-bottom:0.25rem}.meta{color:#636E72;font-size:0.9rem}
table{width:100%;border-collapse:collapse;margin:1rem 0}th,td{text-align:left;padding:0.5rem;border-bottom:1px solid #E8E6F5}
.box{border:1px solid #E8E6F5;border-radius:12px;padding:1rem;margin:1rem 0;background:#FAFAFE}
.badge{display:inline-block;background:#E8F5E9;color:#2E7D32;padding:0.2rem 0.6rem;border-radius:999px;font-size:0.8rem}
.warn{background:#FFF8E1;color:#F57F17}.hash{font-family:ui-monospace,monospace;font-size:0.75rem;word-break:break-all}
@media print{.no-print{display:none}}
</style></head><body>
""");
        sb.Append($"<h1>Donation Receipt</h1>");
        sb.Append($"<p class=\"meta\">Receipt No. <strong>{WebUtility.HtmlEncode(tax.ReceiptNumber)}</strong> · Issued {tax.IssuedAt:u}</p>");

        if (tax.IsEligibleForTaxReceipt)
            sb.Append("<p><span class=\"badge\">Tax-deductible receipt</span></p>");
        else
            sb.Append("<p><span class=\"badge warn\">Not marked as tax-exempt nonprofit receipt</span></p>");

        sb.Append("<div class=\"box\"><h3>Organization</h3>");
        sb.Append($"<p><strong>{WebUtility.HtmlEncode(tax.OrgLegalName ?? campaign.Title)}</strong><br/>");
        sb.Append($"Campaign: {WebUtility.HtmlEncode(campaign.Title)}<br/>");
        if (!string.IsNullOrEmpty(tax.OrgTaxId))
            sb.Append($"Tax ID: {WebUtility.HtmlEncode(tax.OrgTaxId)}<br/>");
        if (!string.IsNullOrEmpty(tax.ExemptionType))
            sb.Append($"Exemption: {WebUtility.HtmlEncode(tax.ExemptionType)} {WebUtility.HtmlEncode(tax.ExemptionNumber)}<br/>");
        sb.Append("</p></div>");

        sb.Append("<div class=\"box\"><h3>Donor</h3><p>");
        sb.Append(WebUtility.HtmlEncode(tax.DonorLegalName ?? "Donor"));
        if (!string.IsNullOrEmpty(tax.DonorAddress)) sb.Append($"<br/>{WebUtility.HtmlEncode(tax.DonorAddress)}");
        if (!string.IsNullOrEmpty(tax.DonorTaxId)) sb.Append($"<br/>Donor Tax ID: {WebUtility.HtmlEncode(tax.DonorTaxId)}");
        sb.Append("</p></div>");

        sb.Append("<table><tr><th>Description</th><th>Amount</th></tr>");
        sb.Append($"<tr><td>Donation to {WebUtility.HtmlEncode(campaign.Title)}<br/><span class=\"meta\">Captured {donation.CapturedAt:u}<br/>PayPal Capture: {WebUtility.HtmlEncode(donation.PayPalCaptureId ?? "—")}</span></td>");
        sb.Append($"<td><strong>{donation.Amount:N2} {WebUtility.HtmlEncode(donation.Currency)}</strong></td></tr></table>");

        sb.Append("""
<p class="meta">This receipt is generated by CrowdFund AI for the donor’s records. Tax deductibility depends on local law and the organization’s exemption status. Consult a tax advisor. CrowdFund AI does not provide tax advice.</p>
""");
        if (!string.IsNullOrEmpty(ledgerHeadHash))
            sb.Append($"<p class=\"hash\">Ledger reference: {WebUtility.HtmlEncode(ledgerHeadHash)}</p>");
        sb.Append("""
<p class="no-print"><button onclick="window.print()">Print / Save as PDF</button></p>
</body></html>
""");
        return sb.ToString();
    }
}
