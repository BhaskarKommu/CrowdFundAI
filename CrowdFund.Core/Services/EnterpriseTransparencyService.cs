using System.Text;
using System.Text.Json;
using CrowdFund.Core.Entities;

namespace CrowdFund.Core.Services;

public class EnterpriseTransparencyService
{
    public PortfolioTransparencyReport BuildPortfolioReport(
        Guid tenantId,
        Guid? enterpriseAccountId,
        IReadOnlyList<Campaign> campaigns,
        IReadOnlyList<Expense> expenses,
        IReadOnlyList<FraudFlag> flags,
        DateTime periodStart,
        DateTime periodEnd,
        string? brandName = null)
    {
        var campIds = campaigns.Select(c => c.Id).ToHashSet();
        var exp = expenses.Where(e => campIds.Contains(e.CampaignId)).ToList();
        var verified = exp.Where(e => e.Status is ExpenseStatus.Verified or ExpenseStatus.AiExtracted).Sum(e => e.Amount);
        var raised = campaigns.Sum(c => c.RaisedAmount);
        var avgTrust = campaigns.Count == 0 ? 0 : campaigns.Average(c => c.TrustScore);
        var avgTrans = campaigns.Count == 0 ? 0 : campaigns.Average(c => c.TransparencyScore);
        var highFlags = flags.Count(f => campIds.Contains(f.CampaignId) && f.Status == "Open" && f.Severity == "High");

        var byCat = campaigns.GroupBy(c => c.Category)
            .Select(g => new { category = g.Key, count = g.Count(), raised = g.Sum(x => x.RaisedAmount) })
            .OrderByDescending(x => x.raised)
            .ToList();

        var sb = new StringBuilder();
        sb.AppendLine($"# Portfolio transparency report");
        if (!string.IsNullOrEmpty(brandName)) sb.AppendLine($"**Organization:** {brandName}");
        sb.AppendLine($"**Period:** {periodStart:yyyy-MM-dd} → {periodEnd:yyyy-MM-dd} UTC");
        sb.AppendLine();
        sb.AppendLine($"- Campaigns in scope: **{campaigns.Count}**");
        sb.AppendLine($"- Total raised: **{raised:N2}**");
        sb.AppendLine($"- Verified spend: **{verified:N2}** ({(raised <= 0 ? 0 : 100m * verified / raised):N1}% of raised)");
        sb.AppendLine($"- Average trust score: **{avgTrust:N1}**");
        sb.AppendLine($"- Average transparency score: **{avgTrans:N1}**");
        sb.AppendLine($"- Open high-severity flags: **{highFlags}**");
        sb.AppendLine();
        sb.AppendLine("## Category mix");
        foreach (var row in byCat.Take(12))
            sb.AppendLine($"- {row.category}: {row.count} campaigns, raised {row.raised:N2}");
        sb.AppendLine();
        sb.AppendLine("_Generated by CrowdFund AI Enterprise Transparency-as-a-Service. Scores are advisory risk indicators, not legal certification._");

        var brandSafe = System.Net.WebUtility.HtmlEncode(brandName ?? "Portfolio");
        var html =
            "<!DOCTYPE html><html><head><meta charset=\"utf-8\"><title>Portfolio transparency</title>" +
            "<style>body{font-family:system-ui,sans-serif;max-width:900px;margin:2rem auto;color:#222}" +
            "h1{color:#6C5CE7} .grid{display:grid;grid-template-columns:repeat(3,1fr);gap:1rem}" +
            ".card{border:1px solid #e8e6f5;border-radius:12px;padding:1rem;background:#fafafe}" +
            ".muted{color:#666;font-size:14px}</style></head><body>" +
            $"<h1>{brandSafe} transparency</h1>" +
            $"<p class=\"muted\">{periodStart:u} – {periodEnd:u}</p>" +
            "<div class=\"grid\">" +
            $"<div class=\"card\"><div class=\"muted\">Campaigns</div><strong>{campaigns.Count}</strong></div>" +
            $"<div class=\"card\"><div class=\"muted\">Raised</div><strong>{raised:N0}</strong></div>" +
            $"<div class=\"card\"><div class=\"muted\">Verified spend</div><strong>{verified:N0}</strong></div>" +
            $"<div class=\"card\"><div class=\"muted\">Avg trust</div><strong>{avgTrust:N0}</strong></div>" +
            $"<div class=\"card\"><div class=\"muted\">Avg transparency</div><strong>{avgTrans:N0}</strong></div>" +
            $"<div class=\"card\"><div class=\"muted\">Open high flags</div><strong>{highFlags}</strong></div>" +
            "</div>" +
            "<p class=\"muted\">Advisory only — not a guarantee of legitimacy.</p>" +
            "</body></html>";

        return new PortfolioTransparencyReport
        {
            TenantId = tenantId,
            EnterpriseAccountId = enterpriseAccountId,
            Title = $"Portfolio transparency — {periodEnd:yyyy-MM-dd}",
            Status = PortfolioReportStatus.Ready,
            CampaignCount = campaigns.Count,
            TotalRaised = raised,
            TotalVerifiedSpend = verified,
            AvgTrustScore = avgTrust,
            AvgTransparencyScore = avgTrans,
            OpenHighFlags = highFlags,
            SummaryMarkdown = sb.ToString(),
            MetricsJson = JsonSerializer.Serialize(new { byCategory = byCat, periodStart, periodEnd }),
            HtmlBody = html,
            PeriodStart = periodStart,
            PeriodEnd = periodEnd,
            CompletedAt = DateTime.UtcNow
        };
    }

    public object ComplianceManifest(
        Tenant tenant,
        IReadOnlyList<Campaign> campaigns,
        IReadOnlyList<Expense> expenses,
        IReadOnlyList<AuditLedgerEntry> ledgerHeads)
    {
        return new
        {
            generatedAt = DateTime.UtcNow,
            tenant = new { tenant.Id, tenant.Slug, tenant.Name },
            campaigns = campaigns.Select(c => new
            {
                c.Id, c.Title, c.Status, c.TrustScore, c.TransparencyScore, c.RaisedAmount, c.GoalAmount, c.Currency
            }),
            expenseCount = expenses.Count,
            verifiedExpenseCount = expenses.Count(e => e.Status is ExpenseStatus.Verified or ExpenseStatus.AiExtracted),
            ledgerHeads = ledgerHeads.Select(l => new { l.CampaignId, l.Hash, l.CreatedAt }),
            disclaimer = "Evidence pack manifest for enterprise compliance review. Pair with original files and tax receipts as required by jurisdiction."
        };
    }
}
